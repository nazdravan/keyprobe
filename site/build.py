#!/usr/bin/env python3
"""Builds the landing page (GitHub Pages) from site/, the latest release and CHANGELOG.md.
Python 3.11+ standard library only.

    gh release view --json tagName,publishedAt,url,assets > release.json
    python3 site/build.py --release release.json --out _site [--app dist]

`--app` copies the web build (`cargo xtask web` → dist/) to _site/app/, the "Run in the browser"
link. Colours and fonts come from assets/theme.toml (written to assets/theme.css), images from
assets/ and docs/assets/. A release missing one of the expected files fails the build, so the
old page, with working links, stays up.
"""
import argparse
import html
import json
import re
import shutil
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITE = ROOT / "site"
SITE_URL = "https://nazdravan.github.io/keyprobe/"
REPO_URL = "https://github.com/nazdravan/keyprobe"
NEWS_COUNT = 3
PLACEHOLDER = re.compile(r"\{\{\{\s*(\w+)\s*\}\}\}|\{\{\s*(\w+)\s*\}\}")
SECTION = re.compile(r"^## \[(?P<version>[^\]]+)\] — (?P<date>\d{4}-\d{2}-\d{2})$", re.M)

# A release's files: the key used in the page -> the end of the name after `keyprobe-<version>-`
# (SHA256SUMS.txt has its full name).
ASSET_KINDS = {
    "win-msi": "windows-x64.msi",
    "win-zip": "windows-x64-portable.zip",
    "mac-dmg": "macos-universal.dmg",
    "linux-appimage": "linux-x86_64.AppImage",
    "linux-deb": "linux-x86_64.deb",
    "linux-tar": "linux-x86_64.tar.gz",
    "sha256": "SHA256SUMS.txt",
}

IMAGES = {
    "logo.png": ROOT / "assets/icon.png",
    "mark.png": ROOT / "docs/assets/keyprobe-mark.png",
    "banner.png": ROOT / "docs/assets/banner.png",
    "og.png": ROOT / "docs/assets/og.png",
    "screenshot-main.png": ROOT / "docs/assets/screenshot-main.png",
    "screenshot-light-iso.png": ROOT / "docs/assets/screenshot-light-iso.png",
    "screenshot-high-contrast-60.png": ROOT / "docs/assets/screenshot-high-contrast-60.png",
    "Ubuntu-Light.ttf": ROOT / "assets/fonts/Ubuntu-Light.ttf",
    "Hack-Regular.ttf": ROOT / "assets/fonts/Hack-Regular.ttf",
}

# The licences of the fonts above travel with them (see NOTICE).
FONT_LICENCES = {
    "UFL.txt": ROOT / "assets/fonts/UFL.txt",
    "Hack-Regular.txt": ROOT / "assets/fonts/Hack-Regular.txt",
}

# CSS custom property -> theme.toml key, for light and dark.
THEME_VARS = {
    "--accent": ("accent", "accent"),
    "--accent-press": ("accent_press", "accent_press"),
    "--held": ("held", "held"),
    "--alert": ("alert", "alert"),
    "--ink": ("ink", "ink"),
    "--bg": ("bg_light", "bg_dark"),
    "--fg": ("fg_light", "fg_dark"),
    "--key": ("key_light", "key_dark"),
    "--select": ("select_light", "select_dark"),
}


def theme_css(theme):
    """assets/theme.css: the theme's colours and fonts as CSS custom properties."""
    def block(index):
        return "".join(f"  {var}: {theme[keys[index]]};\n" for var, keys in THEME_VARS.items())

    fonts = (
        '@font-face { font-family: "{font}"; src: url("Ubuntu-Light.ttf") format("truetype"); '
        "font-weight: 300 400; font-display: swap; }\n"
        '@font-face { font-family: "{mono}"; src: url("Hack-Regular.ttf") format("truetype"); '
        "font-display: swap; }\n"
    ).replace("{font}", theme["font"]).replace("{mono}", theme["mono"])
    return (
        "/* Generated by site/build.py from assets/theme.toml; do not edit. */\n"
        + fonts
        + ":root {\n  color-scheme: light dark;\n"
        + f'  --font: "{theme["font"]}", system-ui, sans-serif;\n'
        + f'  --mono: "{theme["mono"]}", ui-monospace, monospace;\n'
        + block(0)
        + "}\n@media (prefers-color-scheme: dark) {\n  :root {\n"
        + block(1).replace("  --", "    --")
        + "  }\n}\n"
    )


def changelog_sections(md, count):
    """The first `count` versions of the changelog: version, date, body (Markdown)."""
    matches = list(SECTION.finditer(md))[:count]
    sections = []
    for i, m in enumerate(matches):
        end = matches[i + 1].start() if i + 1 < len(matches) else len(md)
        body = md[m.end():end]
        cut = re.search(r"^## |^\[[^\]]+\]: \S+$", body, re.M)
        if cut:
            body = body[:cut.start()]
        sections.append({"version": m["version"], "date": m["date"], "body": body.strip()})
    return sections


def release_assets(release):
    """Key -> {name, url, size}. A missing file stops the build."""
    version = release["tagName"].removeprefix("v")
    by_name = {a["name"]: a for a in release["assets"]}
    assets = {}
    for kind, suffix in ASSET_KINDS.items():
        name = suffix if kind == "sha256" else f"keyprobe-{version}-{suffix}"
        if name not in by_name:
            raise SystemExit(f"release {release['tagName']} has no file {name}")
        a = by_name[name]
        assets[kind] = {"name": name, "url": a["url"], "size": a["size"]}
    return assets


def format_size(n):
    if n < 1024 * 1024:
        return f"{max(1, round(n / 1024))} KB"
    return f"{n / 1024 / 1024:.1f} MB"


def format_date(iso, t):
    y, m, d = (int(x) for x in iso[:10].split("-"))
    return t["date_format"].format(d=d, month=t["months"][m - 1], y=y)


def inline(text):
    """`code`, **bold** and [text](url) on text that is escaped here."""
    out = []
    for part in re.split(r"(`[^`]*`)", text):
        if part.startswith("`") and part.endswith("`") and len(part) > 1:
            out.append(f"<code>{html.escape(part[1:-1], quote=False)}</code>")
            continue
        part = html.escape(part, quote=False)
        part = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", part)
        part = re.sub(
            r"\[([^\]]+)\]\(([^)\s]+)\)",
            lambda m: f'<a href="{html.escape(m[2])}">{m[1]}</a>',
            part,
        )
        out.append(part)
    return "".join(out)


def md_to_html(md):
    """The changelog's Markdown subset: ###, lists with continuation lines, paragraphs."""
    blocks, para, items = [], [], None

    def flush_para():
        if para:
            blocks.append(f"<p>{inline(' '.join(para))}</p>")
            para.clear()

    def flush_list():
        nonlocal items
        if items is not None:
            blocks.append("<ul>" + "".join(f"<li>{inline(i)}</li>" for i in items) + "</ul>")
            items = None

    for line in md.splitlines():
        if line.startswith("### "):
            flush_para()
            flush_list()
            blocks.append(f"<h4>{inline(line[4:].strip())}</h4>")
        elif line.startswith("- "):
            flush_para()
            if items is None:
                items = []
            items.append(line[2:].strip())
        elif line.startswith("  ") and items:
            items[-1] += " " + line.strip()
        elif not line.strip():
            flush_para()
            flush_list()
        else:
            flush_list()
            para.append(line.strip())
    flush_para()
    flush_list()
    return "\n".join(blocks)


def version_key(v):
    return tuple(int(x) for x in re.findall(r"\d+", v.split("-")[0])[:3])


def news_html(md, t, released):
    """The latest versions in the changelog, without ones not yet released (the changelog is
    written before the release)."""
    sections = [s for s in changelog_sections(md, NEWS_COUNT + 5)
                if version_key(s["version"]) <= version_key(released)]
    out = []
    for s in sections[:NEWS_COUNT]:
        out.append(
            f'<article class="release"><div class="release-head"><h3>{html.escape(s["version"])}</h3>'
            f'<time datetime="{s["date"]}">{format_date(s["date"], t)}</time></div>\n'
            f'<div class="release-body">{md_to_html(s["body"])}</div></article>'
        )
    return "\n".join(out)


def render(template, values):
    """{{{ key }}} = raw HTML, {{ key }} = escaped text; a missing key is an error."""
    def sub(m):
        raw, escaped = m[1], m[2]
        value = values[raw or escaped]
        return value if raw else html.escape(value)
    return PLACEHOLDER.sub(sub, template)


def build(release, out, app=None):
    assets = release_assets(release)
    version = release["tagName"].removeprefix("v")
    with open(ROOT / "assets/theme.toml", "rb") as f:
        theme = tomllib.load(f)
    t = json.loads((SITE / "i18n/en.json").read_text(encoding="utf-8"))
    values = {k: v for k, v in t.items() if isinstance(v, str)}
    date = format_date(release["publishedAt"], t)
    values.update({
        "site_url": SITE_URL,
        "repo_url": REPO_URL,
        "version": version,
        "version_html": html.escape(
            t["version_line"].replace("{{ version }}", version).replace("{{ date }}", date)
        ),
        "kinds_json": json.dumps({
            "windows": assets["win-msi"]["url"],
            "mac": assets["mac-dmg"]["url"],
            "linux": assets["linux-appimage"]["url"],
        }),
        "news_html": news_html((ROOT / "CHANGELOG.md").read_text(encoding="utf-8"), t, version),
    })
    for kind, a in assets.items():
        key = kind.replace("-", "_")
        values[f"url_{key}"] = a["url"]
        values[f"name_{key}"] = a["name"]
        values[f"size_{key}"] = format_size(a["size"])

    out.mkdir(parents=True, exist_ok=True)
    template = (SITE / "template.html").read_text(encoding="utf-8")
    (out / "index.html").write_text(render(template, values), encoding="utf-8")
    (out / "assets").mkdir(exist_ok=True)
    for f in (SITE / "assets").iterdir():
        shutil.copy2(f, out / "assets" / f.name)
    (out / "assets/theme.css").write_text(theme_css(theme), encoding="utf-8")
    for name, src in {**IMAGES, **FONT_LICENCES}.items():
        shutil.copy2(src, out / "assets" / name)
    if app is not None:
        if not (app / "index.html").is_file():
            raise SystemExit(f"{app} has no index.html: run `cargo xtask web` first")
        shutil.copytree(app, out / "app", ignore=shutil.ignore_patterns("release", "stage"))
    (out / ".nojekyll").write_text("")


def main():
    p = argparse.ArgumentParser(description="Builds the KeyProbe landing page.")
    p.add_argument("--release", required=True, help="JSON from gh release view --json tagName,publishedAt,url,assets")
    p.add_argument("--out", required=True, help="the folder to write the page to")
    p.add_argument("--app", help="the web build to publish under app/ (cargo xtask web → dist/)")
    args = p.parse_args()
    release = json.loads(Path(args.release).read_text(encoding="utf-8"))
    out = Path(args.out)
    if out.exists():
        shutil.rmtree(out)
    build(release, out, Path(args.app) if args.app else None)
    print(f"done: {out}")


if __name__ == "__main__":
    main()
